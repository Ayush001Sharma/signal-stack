"use client";

import * as React from "react";
import { toast } from "sonner";
import { Bot, CheckCircle2, CornerDownRight, Edit3, EyeOff, Info, Lock, MessagesSquare, RefreshCw, Send, Sparkles, User, Wand2, X } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Progress } from "@/components/ui/progress";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Confirm } from "@/components/shared/confirm";
import { EmptyState, ErrorBanner, ListSkeleton, PageHeader } from "@/components/shared/states";
import { useApi } from "@/hooks/use-api";
import { useCompanyId } from "@/hooks/use-company-id";
import { api, errorMessage, paths } from "@/lib/api";
import type { AnswerChanges, AnsweredBy, InterviewState, Question } from "@/lib/types";
import { cn, fmtDateTime, humanize } from "@/lib/utils";

const ANSWERED_BY: Array<{ value: AnsweredBy; label: string; help: string }> = [
  { value: "founder", label: "Founder", help: "Founder answers become verified profile facts." },
  { value: "team_member", label: "Team member", help: "Stored as a labelled assumption until the founder confirms." },
  { value: "demo_operator", label: "Demo operator — not the founder", help: "Stored as a labelled assumption; use for demos and testing." },
];
const ANSWERED_BY_LABEL: Record<string, string> = { founder: "Founder", team_member: "Team member", demo_operator: "Demo operator" };

function describeChanges(c: AnswerChanges): string[] {
  const out: string[] = [];
  if (c.facts?.length) out.push(`Profile updated: ${c.facts.map(humanize).join(", ")}`);
  if (c.competitors_added?.length) out.push(`Competitors added: ${c.competitors_added.join(", ")}`);
  if (c.competitors_rejected?.length) out.push(`Competitors rejected: ${c.competitors_rejected.join(", ")}`);
  if (c.keywords_added?.length) out.push(`Keywords added: ${c.keywords_added.join(", ")}`);
  return out;
}

function AnsweredByBadge({ who }: { who?: string | null }) {
  if (!who) return null;
  return (
    <Badge tone={who === "founder" ? "emerald" : "amber"} title={who === "founder" ? "Verified founder answer" : "Labelled assumption (not the founder)"}>
      <User className="h-3 w-3" aria-hidden /> {ANSWERED_BY_LABEL[who] ?? humanize(who)}
    </Badge>
  );
}

function GeneratedBy({ by }: { by: string }) {
  const llm = by === "llm";
  return (
    <Badge tone={llm ? "violet" : "slate"} title={llm ? "Question written by the local LLM from your profile" : "Question generated by deterministic rules"}>
      {llm ? <Sparkles className="h-3 w-3" aria-hidden /> : <Bot className="h-3 w-3" aria-hidden />}
      {llm ? "LLM-generated" : "Rule-generated"}
    </Badge>
  );
}

function AnswerForm({
  question,
  parent,
  topicLabel,
  companyId,
  editing,
  onCancelEdit,
  onDone,
}: {
  question: Question;
  parent?: Question;
  topicLabel: string;
  companyId: number;
  editing: boolean;
  onCancelEdit?: () => void;
  onDone: () => void;
}) {
  const [answer, setAnswer] = React.useState(editing ? question.answer ?? "" : "");
  const [who, setWho] = React.useState<AnsweredBy>(((question.answered_by as AnsweredBy) || "founder") as AnsweredBy);
  const [busy, setBusy] = React.useState<"submit" | "skip" | null>(null);
  const [err, setErr] = React.useState<string | null>(null);
  const ref = React.useRef<HTMLTextAreaElement>(null);

  React.useEffect(() => {
    setAnswer(editing ? question.answer ?? "" : "");
    setErr(null);
    ref.current?.focus();
  }, [question.id, editing, question.answer]);

  const submit = async (skip: boolean) => {
    if (!skip && !answer.trim()) {
      setErr("Write an answer, or skip if it's confidential.");
      ref.current?.focus();
      return;
    }
    setErr(null);
    setBusy(skip ? "skip" : "submit");
    try {
      const res = await api.answerQuestion(
        companyId,
        question.id,
        skip ? { skip: true, confidential: true, answered_by: who } : { answer: answer.trim(), answered_by: who },
      );
      const lines = describeChanges(res.changes || {});
      if (res.followup_id) lines.push("A follow-up question was added.");
      if (skip) toast.success("Skipped as confidential", { description: "Recorded as “needs confirmation” — nothing is inferred." });
      else toast.success(editing ? "Answer updated" : "Answer saved", { description: lines.join(" · ") || "Saved to the profile.", duration: 7000 });
      setAnswer("");
      onDone();
    } catch (e) {
      setErr(errorMessage(e));
      toast.error("Could not save answer", { description: errorMessage(e) });
    } finally {
      setBusy(null);
    }
  };

  return (
    <Card className="glow-card">
      <CardHeader>
        <div className="flex flex-wrap items-center gap-1.5">
          <Badge tone="default">{topicLabel}</Badge>
          <GeneratedBy by={question.generated_by} />
          {question.is_followup ? (
            <Badge tone="amber">
              <CornerDownRight className="h-3 w-3" aria-hidden /> Follow-up
            </Badge>
          ) : null}
          {editing ? <Badge tone="blue">Editing previous answer</Badge> : null}
        </div>
        {question.is_followup && parent ? <p className="mt-2 text-xs text-muted-foreground">Following up on: “{parent.question}”</p> : null}
        <h2 className="mt-2 text-lg font-semibold leading-snug" id="q-text">
          {question.question}
        </h2>
        {question.rationale ? (
          <p className="mt-1 flex items-start gap-1.5 text-sm text-muted-foreground">
            <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
            <span>
              <span className="font-medium text-foreground/80">Why we ask this: </span>
              {question.rationale}
            </span>
          </p>
        ) : null}
      </CardHeader>
      <CardContent className="space-y-3">
        <div className="space-y-1.5">
          <Label htmlFor="answer">Your answer</Label>
          <Textarea
            id="answer"
            ref={ref}
            rows={5}
            maxLength={5000}
            value={answer}
            onChange={(e) => setAnswer(e.target.value)}
            onKeyDown={(e) => {
              if ((e.metaKey || e.ctrlKey) && e.key === "Enter") void submit(false);
            }}
            aria-describedby="q-text answer-help"
            aria-invalid={!!err}
            placeholder="Answer in your own words — specifics (names, numbers, places) make monitoring sharper."
          />
          <div id="answer-help" className="flex justify-between text-[11px] text-muted-foreground">
            <span>{err ? <span className="text-rose-500">{err}</span> : "Ctrl/⌘ + Enter to submit"}</span>
            <span className="tabular-nums">{answer.length}/5000</span>
          </div>
        </div>
        <div className="flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
          <div className="space-y-1.5">
            <Label htmlFor="answered-by">Answering as</Label>
            <Select value={who} onValueChange={(v) => setWho(v as AnsweredBy)}>
              <SelectTrigger id="answered-by" className="w-full sm:w-72">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                {ANSWERED_BY.map((o) => (
                  <SelectItem key={o.value} value={o.value}>
                    {o.label}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
            <p className="text-[11px] text-muted-foreground">{ANSWERED_BY.find((o) => o.value === who)?.help}</p>
          </div>
          <div className="flex flex-wrap gap-2">
            {editing ? (
              <Button variant="ghost" onClick={onCancelEdit}>
                <X /> Cancel
              </Button>
            ) : (
              <Button variant="outline" loading={busy === "skip"} disabled={!!busy} onClick={() => submit(true)}>
                <Lock /> Skip (confidential)
              </Button>
            )}
            <Button loading={busy === "submit"} disabled={!!busy} onClick={() => submit(false)}>
              <Send /> {editing ? "Save answer" : "Submit"}
            </Button>
          </div>
        </div>
        <p className="rounded-md bg-muted/40 p-2 text-[11px] text-muted-foreground">
          Answers are stored in your own words and update the profile (competitors, keywords, facts). Nothing you skip is guessed.
        </p>
      </CardContent>
    </Card>
  );
}

export default function InterviewPage() {
  const id = useCompanyId();
  const { data, error, isLoading, mutate } = useApi<InterviewState>(paths.interview(id));
  const [editId, setEditId] = React.useState<number | null>(null);
  const [generating, setGenerating] = React.useState(false);

  const generate = async () => {
    setGenerating(true);
    try {
      const qs = await api.generateInterview(id);
      toast.success("Questions regenerated", { description: `${qs.length} questions in the interview.` });
      setEditId(null);
      await mutate();
    } catch (e) {
      toast.error("Could not generate questions", { description: errorMessage(e) });
    } finally {
      setGenerating(false);
    }
  };

  const labels = data?.topic_labels ?? {};
  const byId = new Map((data?.questions ?? []).map((q) => [q.id, q]));
  const editing = editId ? byId.get(editId) : undefined;
  const current = editing ?? data?.next ?? undefined;
  const total = data?.questions.length ?? 0;
  const doneCount = (data?.progress.answered ?? 0) + (data?.progress.skipped ?? 0);
  const answered = (data?.questions ?? []).filter((q) => q.status !== "pending");

  const regenerate = (
    <Confirm
      title="Regenerate interview questions?"
      description="Only pending (unanswered) questions are replaced. Your existing answers and skipped questions are kept."
      confirmLabel="Regenerate"
      destructive={false}
      onConfirm={generate}
    >
      <Button variant="outline" loading={generating}>
        <RefreshCw /> Regenerate questions
      </Button>
    </Confirm>
  );

  return (
    <div>
      <PageHeader
        eyebrow="Adaptive AI interview"
        title="Founder interview"
        description="Short, targeted questions about what public research can't see. Each answer sharpens what we monitor."
        actions={total ? regenerate : null}
      />
      {error ? <ErrorBanner error={error} onRetry={() => mutate()} /> : null}
      {isLoading ? (
        <ListSkeleton rows={2} />
      ) : !data || total === 0 ? (
        <EmptyState
          icon={MessagesSquare}
          title="No interview questions yet"
          description="Questions are generated from the researched profile. If setup is still running, they'll appear shortly — or generate them now."
          action={
            <Button loading={generating} onClick={generate}>
              <Wand2 /> Generate questions
            </Button>
          }
        />
      ) : (
        <div className="grid gap-6 xl:grid-cols-[1fr_380px]">
          <div className="space-y-4">
            <Card className="p-4">
              <div className="mb-2 flex flex-wrap items-center justify-between gap-2 text-sm">
                <span className="font-medium">
                  {doneCount} of {total} questions handled
                </span>
                <span className="text-xs text-muted-foreground">
                  {data.progress.answered} answered · {data.progress.skipped} skipped · {data.progress.pending} pending · {data.progress.followups} follow-ups
                </span>
              </div>
              <Progress value={total ? (doneCount / total) * 100 : 0} aria-label="Interview progress" />
            </Card>
            {current ? (
              <AnswerForm
                key={`${current.id}-${editing ? "edit" : "new"}`}
                question={current}
                parent={current.parent_id ? byId.get(current.parent_id) : undefined}
                topicLabel={labels[current.topic] ?? humanize(current.topic)}
                companyId={id}
                editing={!!editing}
                onCancelEdit={() => setEditId(null)}
                onDone={() => {
                  setEditId(null);
                  void mutate();
                }}
              />
            ) : (
              <EmptyState
                icon={CheckCircle2}
                title="Interview complete"
                description="Every question has been answered or skipped. You can edit any answer from the history, or regenerate to get fresh questions for anything still pending."
                action={regenerate}
              />
            )}
          </div>
          <aside aria-labelledby="hist-h">
            <Card>
              <CardHeader>
                <CardTitle id="hist-h">Answer history</CardTitle>
                <CardDescription>{answered.length ? "Select “Edit answer” to revise; edits re-apply to the profile." : "Answered questions will appear here."}</CardDescription>
              </CardHeader>
              <CardContent className="max-h-[70vh] space-y-3 overflow-y-auto">
                {data.questions.map((q) => (
                  <div
                    key={q.id}
                    className={cn(
                      "rounded-lg border p-3 text-sm",
                      q.is_followup && "ml-4 border-dashed",
                      current?.id === q.id && "border-primary/50 bg-primary/5",
                      q.status === "pending" && current?.id !== q.id && "opacity-60",
                    )}
                  >
                    <div className="mb-1 flex flex-wrap items-center gap-1">
                      <Badge tone="outline">{labels[q.topic] ?? humanize(q.topic)}</Badge>
                      {q.status === "answered" ? <Badge tone="emerald">Answered</Badge> : q.status === "skipped" ? <Badge tone="slate"><EyeOff className="h-3 w-3" aria-hidden /> Skipped{q.confidential ? " · confidential" : ""}</Badge> : <Badge tone="amber">Pending</Badge>}
                      {q.status !== "pending" ? <AnsweredByBadge who={q.answered_by} /> : null}
                      {q.is_followup ? <Badge tone="amber">Follow-up</Badge> : null}
                    </div>
                    <p className="font-medium leading-snug">{q.question}</p>
                    {q.answer ? <p className="mt-1.5 line-clamp-4 whitespace-pre-line text-xs text-muted-foreground">“{q.answer}”</p> : null}
                    {q.status !== "pending" ? (
                      <div className="mt-2 flex items-center justify-between">
                        <span className="text-[11px] text-muted-foreground">{fmtDateTime(q.answered_at)}</span>
                        <Button variant="ghost" size="xs" onClick={() => setEditId(q.id)} aria-label={`Edit answer to: ${q.question.slice(0, 50)}`}>
                          <Edit3 className="h-3 w-3" /> Edit answer
                        </Button>
                      </div>
                    ) : null}
                  </div>
                ))}
              </CardContent>
            </Card>
          </aside>
        </div>
      )}
    </div>
  );
}
